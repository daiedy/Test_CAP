// docs-toolchain (ADR-0029): the documentation of the model, the API and the code reaches its consumers.
// Decision 2: the CDS doc comment is the only description mechanism of the project; with cds.cdsc.docs
// the compiled CSN keeps it as `doc`, the EDMX and the OpenAPI export turn it into a description.
// Plan step 3 extends this file with the OpenAPI document, JSDOC.md and Swagger UI tests.
import cds from '@sap/cds';
import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
// These tests read the model and start no server: switch cds.root (and with it cds.env) only.
cds.test.in(root);

// Elements the project does not describe: the technical key ID (of cuid and of the Permissions
// singleton), the admin data of `managed` (createdBy and modifiedBy carry SAP's @description), and the
// texts/localized associations the compiler generates for localized elements.
const UNDESCRIBED = new Set([
  'ID',
  'createdAt',
  'createdBy',
  'modifiedAt',
  'modifiedBy',
  'texts',
  'localized',
]);

// The description annotations ADR-0029 decision 2 forbids in project CDS, with or without a qualifier.
const DESCRIPTION_ANNOTATION = /^@(description|Core\.Description|Core\.LongDescription)(#|$)/;

const described = (definition) => typeof definition?.doc === 'string' && /\S/.test(definition.doc);

// Every .cds file of the project model under db/, srv/ and app/, without node_modules.
const cdsFiles = (dir) =>
  readdirSync(path.join(root, dir), { withFileTypes: true }).flatMap((entry) => {
    const file = path.posix.join(dir, entry.name);
    if (entry.isDirectory()) return entry.name === 'node_modules' ? [] : cdsFiles(file);
    return entry.name.endsWith('.cds') ? [file] : [];
  });

// The keys naming a forbidden description annotation anywhere in a parsed CSN. The parser flattens
// @(description: ...) and @Core: { Description: ... } into these keys and drops comments.
const descriptionAnnotations = (node, found = []) => {
  if (node && typeof node === 'object') {
    for (const [key, value] of Object.entries(node)) {
      if (DESCRIPTION_ANNOTATION.test(key)) found.push(key);
      descriptionAnnotations(value, found);
    }
  }
  return found;
};

describe('Descriptions of CatalogService in the model', () => {
  // Asserted on the CSN `doc`, not on Core.Description: `currency`, `createdBy` and `modifiedBy`
  // get SAP's Core.Description from @sap/cds/common, which says nothing about the project's comment.
  it('documents every exposed entity and element with a doc comment and never with @description', async () => {
    const csn = await cds.load('*');
    const definitions = Object.entries(csn.definitions);
    // The project projections: entities of the service on a my.catalog entity. The auto-exposed
    // Currencies and .texts entities are SAP's or generated by the compiler.
    const projections = definitions.filter(
      ([name, d]) =>
        name.startsWith('CatalogService.') &&
        d.kind === 'entity' &&
        !d['@cds.autoexposed'] &&
        (d.projection ?? d.query?.SELECT)?.from?.ref?.[0]?.startsWith('my.catalog.')
    );
    expect(projections.map(([name]) => name)).toEqual(
      expect.arrayContaining(
        [
          'Products',
          'ProductDetails',
          'ProductDetailSelections',
          'Categories',
          'Subcategories',
          'DetailValueTypes',
          'DetailAttributes',
          'DetailListValues',
          'SubcategoryAttributes',
        ].map((entity) => `CatalogService.${entity}`)
      )
    );
    // The singleton and the action's parameter type are defined in the service file itself.
    const structured = [
      ...projections,
      ...['CatalogService.Permissions', 'CatalogService.ProductsImportFile'].map((name) => [
        name,
        csn.definitions[name],
      ]),
    ];
    const importProducts = csn.definitions['CatalogService.Products'].actions.importProducts;

    const undocumented = [];
    if (!described(csn.definitions.CatalogService)) undocumented.push('CatalogService');
    for (const [name, d] of structured) {
      if (!described(d)) undocumented.push(name);
      for (const [element, definition] of Object.entries(d.elements)) {
        if (!UNDESCRIBED.has(element) && !described(definition)) {
          undocumented.push(`${name}/${element}`);
        }
      }
    }
    if (!described(importProducts)) undocumented.push('CatalogService.importProducts');
    for (const [param, definition] of Object.entries(importProducts.params)) {
      if (!described(definition)) undocumented.push(`CatalogService.importProducts/${param}`);
    }
    expect(undocumented).toEqual([]);

    // Never written as an annotation: every project .cds file is parsed on its own, so the
    // @description that createdBy, modifiedBy and currency inherit from @sap/cds/common is not seen.
    const files = ['db', 'srv', 'app'].flatMap(cdsFiles);
    expect(files).toEqual(
      expect.arrayContaining([
        'db/schema.cds',
        'srv/catalog-service.cds',
        'srv/annotations/Products.cds',
        'app/products/annotations.cds',
        'app/products/annotations/Products.cds',
      ])
    );
    const written = files.flatMap((file) =>
      descriptionAnnotations(cds.parse.cdl(readFileSync(path.join(root, file), 'utf8'))).map(
        (annotation) => `${file}: ${annotation}`
      )
    );
    expect(written).toEqual([]);
  });
});
