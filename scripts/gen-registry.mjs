#!/usr/bin/env node
// Generates docs/registry/*.md from the effective CDS model and project sources.
// Output files are overwritten; never edit them by hand. Run: npm run docs:registry
import cds from '@sap/cds';
import {
  readFileSync,
  writeFileSync,
  existsSync,
  mkdirSync,
  rmSync,
  readdirSync,
  statSync,
} from 'node:fs';
import { join, relative, sep } from 'node:path';
import { spawnSync } from 'node:child_process';
import { sourcesHash } from './lib/registry-sources.mjs';

const ROOT = process.cwd();
cds.root = ROOT;
const OUT = join(ROOT, 'docs/registry');
mkdirSync(OUT, { recursive: true });
const HASH = sourcesHash(ROOT);
const DATE = new Date().toISOString().slice(0, 10);
const header = (title, note) =>
  `<!-- generated by scripts/gen-registry.mjs | sources: ${HASH} | ${DATE} | do not edit -->\n# ${title}\n\n${note}\n\n`;

// ---------- helpers ----------
const rel = (p) => relative(ROOT, p).split(sep).join('/');
function walk(dir, acc = []) {
  if (!existsSync(dir)) return acc;
  for (const n of readdirSync(dir)) {
    if (['node_modules', 'dist', 'gen', '.git'].includes(n)) continue;
    const f = join(dir, n);
    statSync(f).isDirectory() ? walk(f, acc) : acc.push(f);
  }
  return acc;
}
function loadProps(file) {
  const map = {};
  if (!existsSync(file)) return map;
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const i = t.indexOf('=');
    if (i > 0) map[t.slice(0, i).trim()] = t.slice(i + 1).trim();
  }
  return map;
}
const I18N = {
  ...loadProps(join(ROOT, 'node_modules/@sap/cds/_i18n/i18n.properties')),
  ...loadProps(join(ROOT, '_i18n/i18n.properties')),
};
const text = (v) => {
  if (v == null) return '';
  const s = typeof v === 'object' && '=' in v ? v['='] : String(v);
  return s.replace(/\{i18n>([^}]+)\}/g, (_, k) => I18N[k] ?? `{i18n>${k}}`);
};
const esc = (s) =>
  String(s ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ');
const table = (head, rows) =>
  rows.length
    ? `| ${head.join(' | ')} |\n| ${head.map(() => '---').join(' | ')} |\n` +
      rows.map((r) => `| ${r.map(esc).join(' | ')} |`).join('\n') +
      '\n'
    : '_нет_\n';
function typeOf(el) {
  if (el.type === 'cds.Association' || el.type === 'cds.Composition') {
    const kind = el.type === 'cds.Composition' ? 'Composition of' : 'Association to';
    const many = el.cardinality?.max === '*' ? 'many ' : '';
    return `${kind} ${many}${el.target}`;
  }
  let t = (el.type || '').replace(/^cds\./, '');
  if (el.length) t += `(${el.length})`;
  else if (el.precision) t += `(${el.precision}${el.scale != null ? `, ${el.scale}` : ''})`;
  if (el.enum) t += ' enum';
  return t || (el.elements ? 'structured' : '');
}
function annots(el) {
  const out = [];
  if (el.key) out.push('key');
  if (el['@mandatory']) out.push('@mandatory');
  if (el['@readonly']) out.push('@readonly');
  if (el['@Core.Computed']) out.push('computed');
  for (const k of Object.keys(el)) {
    if (k.startsWith('@assert.')) out.push(`${k}: ${JSON.stringify(el[k])}`);
    if (k === '@Measures.ISOCurrency') out.push(`${k}: ${el[k]['=']}`);
  }
  return out.join(', ');
}

// ---------- model ----------
const csn = await cds.load('*');
const m = cds.linked(cds.compile.for.nodejs(csn));
const isForeign = (n) => /^(sap\.common\.|cds\.|localized\.|DRAFT\.)/.test(n);
const services = Object.values(m.definitions).filter((d) => d.kind === 'service');
const svcPrefixes = services.map((s) => s.name + '.');
const inService = (n) => svcPrefixes.find((p) => n.startsWith(p));

// ---------- DOMAIN-MODEL.md ----------
{
  let md = header(
    'Доменная модель',
    'Эффективная модель после компиляции: сущности, элементы, типы и аспекты проекта. Источник истины это `db/*.cds` и `srv/annotations/*.cds`; здесь только их отражение. Для точечного поиска используй `mcp__cds-mcp__search_model`.'
  );
  const mermaid = spawnSync('npx', ['cds', 'compile', 'db', '--to', 'mermaid'], {
    cwd: ROOT,
    encoding: 'utf8',
    timeout: 60000,
  });
  if (mermaid.status === 0 && mermaid.stdout.trim()) {
    const body = mermaid.stdout.trim();
    md +=
      '## Диаграмма\n\n' +
      (body.startsWith('```') ? body : '```mermaid\n' + body + '\n```') +
      '\n\n';
  }
  const entities = Object.values(m.definitions).filter(
    (d) => d.kind === 'entity' && !isForeign(d.name) && !inService(d.name)
  );
  // Titles live on service projections (srv/annotations); map source entity -> first projection.
  const projectionOf = {};
  for (const d of Object.values(m.definitions)) {
    if (d.kind !== 'entity' || !inService(d.name)) continue;
    const from = d.query?.SELECT?.from?.ref?.join('.') ?? d.projection?.from?.ref?.join('.');
    if (from && !projectionOf[from]) projectionOf[from] = d;
  }
  const titleOf = (e, el) => {
    const p = projectionOf[e.name]?.elements?.[el.name];
    return text(el['@title'] ?? el['@Common.Label'] ?? p?.['@title'] ?? p?.['@Common.Label']);
  };
  md += '## Сущности\n\n';
  for (const e of entities) {
    const includes = (e.includes || []).join(', ');
    md += `### ${e.name}\n\n`;
    if (e.doc) md += `${e.doc.trim()}\n\n`;
    md += `Аспекты: ${includes || 'нет'}. Ключи: ${Object.values(e.elements)
      .filter((x) => x.key)
      .map((x) => x.name)
      .join(', ')}. Проекции: ${
      Object.values(m.definitions)
        .filter(
          (d) =>
            d.kind === 'entity' &&
            inService(d.name) &&
            (d.query?.SELECT?.from?.ref?.join('.') ?? d.projection?.from?.ref?.join('.')) === e.name
        )
        .map((d) => d.name)
        .join(', ') || 'нет'
    }.\n\n`;
    md +=
      table(
        ['Элемент', 'Тип', 'Название (en)', 'Аннотации'],
        Object.values(e.elements).map((el) => [
          el.name,
          typeOf(el),
          titleOf(e, el),
          annots(projectionOf[e.name]?.elements?.[el.name] ?? el) || annots(el),
        ])
      ) + '\n';
  }
  const types = Object.values(m.definitions).filter(
    (d) => (d.kind === 'type' || d.kind === 'aspect') && !isForeign(d.name) && !inService(d.name)
  );
  md +=
    '## Типы и аспекты проекта\n\n' +
    table(
      ['Имя', 'Вид', 'Определение'],
      types.map((t) => [
        t.name,
        t.kind,
        t.elements ? Object.keys(t.elements).join(', ') : typeOf(t),
      ])
    ) +
    '\n';
  md +=
    '## Переиспользуемые аспекты из @sap/cds/common\n\n`cuid` (key ID : UUID), `managed` (createdAt, createdBy, modifiedAt, modifiedBy), `temporal`, `Currency`, `Country`, `Language`, `sap.common.CodeList`. Использовать их, а не свои копии.\n';
  writeFileSync(join(OUT, 'DOMAIN-MODEL.md'), md);
}

// ---------- SERVICES.md ----------
{
  let md = header(
    'Сервисы и контракт OData',
    'Что выставлено наружу: сервисы, проекции, действия, функции, UI-аннотации по сущностям. Перед добавлением проекции или действия проверь, нет ли уже подходящего.'
  );
  for (const s of services) {
    const path =
      s['@path'] ??
      '/odata/v4/' +
        s.name
          .replace(/^.*\./, '')
          .replace(/Service$/, '')
          .replace(/^./, (c) => c.toLowerCase());
    md += `## ${s.name}\n\nПуть: \`${path}\`. Файл: \`${s.$location?.file ?? 'srv/'}\`. `;
    md += `Авторизация: ${s['@requires'] ? '@requires ' + JSON.stringify(s['@requires']) : 'не задана (по умолчанию открыт при mocked auth)'}.\n\n`;
    const ents = Object.values(m.definitions).filter(
      (d) => d.kind === 'entity' && d.name.startsWith(s.name + '.')
    );
    md +=
      '### Сущности\n\n' +
      table(
        ['Проекция', 'Источник', 'Режим', 'UI', 'Value help', 'Ограничения'],
        ents.map((e) => {
          const from =
            e.query?.SELECT?.from?.ref?.join('.') ?? e.projection?.from?.ref?.join('.') ?? '';
          const auto = e['@cds.autoexposed'] ? 'autoexposed' : '';
          const mode =
            [
              e['@readonly'] && '@readonly',
              e['@insertonly'] && '@insertonly',
              e['@odata.draft.enabled'] && 'draft',
              auto,
            ]
              .filter(Boolean)
              .join(', ') || 'CRUD';
          const ui = [
            e['@UI.LineItem'] && `LineItem(${e['@UI.LineItem'].length})`,
            e['@UI.SelectionFields'] && `SelectionFields(${e['@UI.SelectionFields'].length})`,
            e['@UI.HeaderInfo'] && 'HeaderInfo',
            e['@UI.Facets'] && `Facets(${e['@UI.Facets'].length})`,
            ...Object.keys(e)
              .filter((k) => k.startsWith('@UI.FieldGroup#'))
              .map((k) => k.replace('@UI.', '')),
          ]
            .filter(Boolean)
            .join(', ');
          const vh = Object.values(e.elements)
            .filter((x) => x['@Common.ValueList'])
            .map((x) => `${x.name} → ${x['@Common.ValueList'].CollectionPath}`)
            .join(', ');
          const restr = e['@restrict'] ? '@restrict ' + JSON.stringify(e['@restrict']) : '';
          return [e.name.slice(s.name.length + 1), from, mode, ui, vh, restr];
        })
      ) +
      '\n';
    const bound = ents.flatMap((e) =>
      Object.values(e.actions || {}).map((a) => [
        e.name.slice(s.name.length + 1),
        a.name,
        a.kind,
        Object.keys(a.params || {}).join(', '),
        a.returns ? typeOf(a.returns) : '',
      ])
    );
    const unbound = Object.values(m.definitions)
      .filter(
        (d) => (d.kind === 'action' || d.kind === 'function') && d.name.startsWith(s.name + '.')
      )
      .map((a) => [
        '(сервис)',
        a.name.slice(s.name.length + 1),
        a.kind,
        Object.keys(a.params || {}).join(', '),
        a.returns ? typeOf(a.returns) : '',
      ]);
    md +=
      '### Действия и функции\n\n' +
      table(['Сущность', 'Имя', 'Вид', 'Параметры', 'Возвращает'], [...bound, ...unbound]) +
      '\n';
  }
  writeFileSync(join(OUT, 'SERVICES.md'), md);
}

// ---------- HANDLERS.md ----------
{
  let md = header(
    'Хендлеры',
    'Программная логика в `srv/**/*.js`: какие события и сущности уже обрабатываются. Перед новым хендлером проверь, нет ли обработчика того же события.'
  );
  const files = walk(join(ROOT, 'srv')).filter((f) => f.endsWith('.js') && !f.includes('/lib/'));
  const rows = [];
  const re =
    /\b(?:this|srv|service)\s*\.\s*(before|on|after)\s*\(\s*(['"`][^'"`]+['"`]|\[[^\]]*\]|[\w.]+)\s*(?:,\s*(['"`][^'"`]+['"`]|[\w.]+))?/g;
  for (const f of files) {
    const src = readFileSync(f, 'utf8');
    let mm;
    while ((mm = re.exec(src))) {
      const line = src.slice(0, mm.index).split('\n').length;
      rows.push([
        rel(f) + ':' + line,
        mm[1],
        mm[2].replace(/['"`]/g, ''),
        (mm[3] || '(сервис)').replace(/['"`]/g, ''),
      ]);
    }
    const cdsOn = /\bcds\.on\s*\(\s*['"`]([^'"`]+)['"`]/g;
    while ((mm = cdsOn.exec(src))) rows.push([rel(f), 'cds.on', mm[1], '(сервер)']);
  }
  md += table(['Файл:строка', 'Фаза', 'Событие', 'Сущность'], rows) + '\n';
  md += `Файлы хендлеров: ${files.length ? files.map((f) => '`' + rel(f) + '`').join(', ') : 'нет, вся логика декларативная'}.\n`;
  writeFileSync(join(OUT, 'HANDLERS.md'), md);
}

// ---------- REUSE-CATALOG.md ----------
{
  let md = header(
    'Каталог переиспользования',
    'Утилиты `srv/lib`, общие типы и аспекты, наборы текстов. Правило: прежде чем писать новую функцию, найди её здесь и через `mcp__cds-mcp__search_model`.'
  );
  const libFiles = walk(join(ROOT, 'srv/lib')).filter((f) => f.endsWith('.js'));
  const rows = [];
  for (const f of libFiles) {
    const src = readFileSync(f, 'utf8');
    const exp =
      /(?:\/\*\*([\s\S]*?)\*\/\s*)?export\s+(?:async\s+)?(?:function|const|class)\s+(\w+)/g;
    let mm;
    while ((mm = exp.exec(src))) {
      const doc =
        (mm[1] || '')
          .split('\n')
          .map((l) => l.replace(/^\s*\*\s?/, '').trim())
          .filter((l) => l && !l.startsWith('@'))[0] || '';
      rows.push([rel(f), mm[2], doc]);
    }
    const named = /export\s*\{([^}]+)\}/g;
    while ((mm = named.exec(src)))
      for (const n of mm[1].split(','))
        rows.push([
          rel(f),
          n
            .trim()
            .split(/\s+as\s+/)
            .pop(),
          '',
        ]);
  }
  md += '## Функции srv/lib\n\n' + table(['Файл', 'Экспорт', 'Назначение'], rows) + '\n';
  const types = Object.values(m.definitions).filter(
    (d) => (d.kind === 'type' || d.kind === 'aspect') && !isForeign(d.name) && !inService(d.name)
  );
  md +=
    '## Общие типы и аспекты проекта\n\n' +
    table(
      ['Имя', 'Вид'],
      types.map((t) => [t.name, t.kind])
    ) +
    '\n';
  const bundles = [
    ...walk(join(ROOT, '_i18n')),
    ...walk(join(ROOT, 'app')).filter((f) => /webapp\/i18n\/i18n(_\w+)?\.properties$/.test(f)),
  ].filter((f) => f.endsWith('.properties'));
  md +=
    '## Наборы текстов (i18n)\n\n' +
    table(
      ['Файл', 'Ключей'],
      bundles.map((f) => [rel(f), String(Object.keys(loadProps(f)).length)])
    ) +
    '\n';
  writeFileSync(join(OUT, 'REUSE-CATALOG.md'), md);
}

// ---------- UI-ARTIFACTS.md ----------
{
  let md = header(
    'UI-артефакты',
    'Приложения в `app/`: шаблоны страниц, источники данных, расширения, фрагменты, форматтеры, тесты. Перед созданием extension или фрагмента проверь, нет ли уже подходящего.'
  );
  const appDir = join(ROOT, 'app');
  const apps = existsSync(appDir)
    ? readdirSync(appDir).filter((a) => existsSync(join(appDir, a, 'webapp/manifest.json')))
    : [];
  for (const app of apps) {
    const base = join(appDir, app);
    const mf = JSON.parse(readFileSync(join(base, 'webapp/manifest.json'), 'utf8'));
    const i18n = loadProps(join(base, 'webapp/i18n/i18n.properties'));
    const t = (v) => String(v ?? '').replace(/\{\{(\w+)\}\}/g, (_, k) => i18n[k] ?? k);
    md += `## app/${app}\n\n`;
    md += `Id: \`${mf['sap.app']?.id}\`. Название: ${t(mf['sap.app']?.title)}. manifest \`_version\`: ${mf._version}. minUI5Version: ${mf['sap.ui5']?.dependencies?.minUI5Version}. Библиотеки: ${Object.keys(mf['sap.ui5']?.dependencies?.libs || {}).join(', ')}.\n\n`;
    md +=
      '### Источники данных\n\n' +
      table(
        ['Имя', 'URI', 'OData'],
        Object.entries(mf['sap.app']?.dataSources || {}).map(([k, v]) => [
          k,
          v.uri,
          v.settings?.odataVersion ?? '',
        ])
      ) +
      '\n';
    const targets = mf['sap.ui5']?.routing?.targets || {};
    const routes = mf['sap.ui5']?.routing?.routes || [];
    md +=
      '### Страницы\n\n' +
      table(
        ['Target', 'Шаблон', 'contextPath', 'Маршрут', 'Настройки'],
        Object.entries(targets).map(([k, v]) => {
          const r = routes.find(
            (x) => x.target === k || (Array.isArray(x.target) && x.target.includes(k))
          );
          const s = v.options?.settings || {};
          const extra = Object.keys(s)
            .filter((x) => !['contextPath', 'navigation', 'enhanceI18n'].includes(x))
            .map((x) => `${x}=${JSON.stringify(s[x])}`)
            .join(', ');
          return [
            k,
            v.name ?? v.viewName ?? '',
            s.contextPath ?? s.entitySet ?? '',
            r?.pattern ?? '',
            extra,
          ];
        })
      ) +
      '\n';
    const ctrlExt = mf['sap.ui5']?.extends?.extensions?.['sap.ui.controllerExtensions'] || {};
    const files = walk(join(base, 'webapp')).filter((f) => !f.includes('/localService/'));
    const exts = files.filter((f) => f.includes('/ext/')).map((f) => rel(f));
    const frags = files.filter((f) => f.endsWith('.fragment.xml')).map((f) => rel(f));
    const views = files.filter((f) => f.endsWith('.view.xml')).map((f) => rel(f));
    md +=
      '### Расширения и фрагменты\n\n' +
      table(
        ['Вид', 'Файл или ключ'],
        [
          ...Object.keys(ctrlExt).map((k) => ['controllerExtension (manifest)', k]),
          ...exts.map((f) => ['ext/', f]),
          ...frags.filter((f) => !f.includes('/ext/')).map((f) => ['fragment', f]),
          ...views.map((f) => ['view', f]),
        ]
      ) +
      '\n';
    const fmt = join(base, 'webapp/model/formatter.js');
    if (existsSync(fmt)) {
      const src = readFileSync(fmt, 'utf8');
      const names = [...src.matchAll(/^\s*(\w+)\s*(?::\s*function|\()/gm)]
        .map((x) => x[1])
        .filter((n) => !['return', 'function'].includes(n));
      md += '### Форматтеры\n\n' + names.map((n) => `- \`${n}\``).join('\n') + '\n\n';
    }
    const comp = join(base, 'webapp/Component.js');
    if (existsSync(comp)) {
      const src = readFileSync(comp, 'utf8');
      const custom =
        src.split('\n').length > 12 ? 'содержит кастомную логику (см. файл)' : 'стандартный';
      md += `### Component.js\n\n${custom}.\n\n`;
    }
    const tests = ['unit', 'integration', 'e2e'].filter((d) =>
      existsSync(join(base, 'webapp/test', d))
    );
    md += `### Тесты\n\n${tests.length ? tests.map((d) => '`webapp/test/' + d + '`').join(', ') : 'нет'}. Мок-режим: ${existsSync(join(base, 'ui5-mock.yaml')) ? '`ui5-mock.yaml` + `webapp/localService`' : 'нет'}.\n\n`;
  }
  writeFileSync(join(OUT, 'UI-ARTIFACTS.md'), md);
}

rmSync(join(OUT, '.stale'), { force: true });
console.log(`docs/registry обновлён (sources ${HASH}).`);
